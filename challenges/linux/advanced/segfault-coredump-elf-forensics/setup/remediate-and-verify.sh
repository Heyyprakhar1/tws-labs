#!/usr/bin/env bash
set -euo pipefail

TARGET_DIR="${HOME:-/root}/segfault-incident"
mkdir -p "$TARGET_DIR/reports"

cat << 'EOF' > "$TARGET_DIR/reports/elf-triage.env"
ELF_CLASS=ELF64
DATA_ENCODING=2LSB
ARCHITECTURE=x86_64
CORE_PROCESS_NAME=worker_service
CRASHED_PID=12480
TERMINATING_SIGNAL=SIGSEGV
SIGNAL_NUMBER=11
SHELL_EXIT_STATUS=139
EOF

cat << 'EOF' > "$TARGET_DIR/reports/fault-analysis.env"
FAULT_ADDRESS=0x0
FAULTING_RIP=0x000055d7a81211e4
CRASHING_RAX=0x0000000000000000
SIGNAL_CODE_NAME=SEGV_MAPERR
SIGNAL_CODE_VALUE=1
KERNEL_ERROR_CODE=4
ERROR_CODE_P_BIT=0
ERROR_CODE_WR_BIT=0
ERROR_CODE_US_BIT=1
VIOLATION_CATEGORY=USER_READ_UNMAPPED_PAGE
EOF

cat << 'EOF' > "$TARGET_DIR/reports/root-cause.env"
FAULTING_FUNCTION=process_batch
VULNERABLE_STRUCT_MEMBER=telemetry_endpoint
ROOT_CAUSE=UNCHECKED_NULL_POINTER_DEREFERENCE
TRIGGERING_CONFIG_KEY=TELEMETRY_ENDPOINT
EOF

cat << 'EOF' > "$TARGET_DIR/config/worker.env"
# Production Batch Worker Configuration
BATCH_SIZE=100
WORKER_CONCURRENCY=4
DATABASE_URL="postgres://app:secret@db.internal:5432/batches"
TELEMETRY_ENABLED="false"
EOF

"$TARGET_DIR/bin/verify-worker"
